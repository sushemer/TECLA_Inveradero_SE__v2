#ifndef TECLA_SENSOR_PROFILE_H
#define TECLA_SENSOR_PROFILE_H

/* Build-time hardware capability profiles; never a physical or SQL node ID. */
#define TECLA_SENSOR_PROFILE_DHT22_ONLY 1
#define TECLA_SENSOR_PROFILE_DHT22_VEML7700 2
#define TECLA_SENSOR_PROFILE_SEN0193_4CH_DECLARED 4

#ifndef TECLA_SENSOR_PROFILE_ID
#error "TECLA_SENSOR_PROFILE_ID debe seleccionarse desde el perfil de build"
#endif

#if TECLA_SENSOR_PROFILE_ID == TECLA_SENSOR_PROFILE_DHT22_ONLY
#define TECLA_PROFILE_HAS_DHT22 1
#define TECLA_PROFILE_HAS_VEML7700 0
#define TECLA_PROFILE_HAS_SEN0193 0
#define TECLA_PROFILE_SENSOR_MASK (1U << 0U)
#elif TECLA_SENSOR_PROFILE_ID == TECLA_SENSOR_PROFILE_DHT22_VEML7700
#define TECLA_PROFILE_HAS_DHT22 1
#define TECLA_PROFILE_HAS_VEML7700 1
#define TECLA_PROFILE_HAS_SEN0193 0
#define TECLA_PROFILE_SENSOR_MASK ((1U << 0U) | (1U << 5U))
#elif TECLA_SENSOR_PROFILE_ID == TECLA_SENSOR_PROFILE_SEN0193_4CH_DECLARED
#define TECLA_PROFILE_HAS_DHT22 0
#define TECLA_PROFILE_HAS_VEML7700 0
#define TECLA_PROFILE_HAS_SEN0193 1
#define TECLA_PROFILE_SENSOR_MASK ((1U << 1U) | (1U << 2U) | (1U << 3U) | (1U << 4U))
#else
#error "TECLA_SENSOR_PROFILE_ID desconocido"
#endif

#endif
